/**
 * §37 — generates the crash-message allowlist from the source that throws them.
 *
 * Inlet's `defaultRedaction` is a SHAPE allowlist for engine-generated messages
 * ("x is not a function"), which is exactly backwards for us: it keeps the
 * messages where the stack already tells you everything, and redacts every
 * sentence HappyVibe's own code authors — which are the diagnostic ones.
 * Measured on 20 realistic errors: 7 survived, and all 7 were the engine's.
 *
 * The invariant that makes extending it safe, and the only reason this is
 * generated rather than hand-listed: **a plain string literal cannot contain
 * runtime data.** No interpolation, no concatenation — what is in the source is
 * exactly what travels. A template literal (`new Error(`… ${x}`)`) is therefore
 * REFUSED here, and `tests/crash-safe-messages.test.ts` re-derives this file
 * from source so a new throw either joins the list or fails the gate.
 *
 * Run: npm run catalog:crash-messages
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOTS = ["src/main", "src/renderer/src"];
const OUT = "src/main/crash/safeMessages.generated.ts";

/** A literal argument only: "…" or '…' immediately closed. Never a backtick. */
const LITERAL = /new Error\(\s*(["'])((?:(?!\1)[^\\]|\\.)*)\1\s*\)/g;

/** Refused even as a literal — a hardcoded path or secret is still content. */
const SUSPECT = [
  { re: /\/Users\/|\/home\/|[A-Za-z]:\\/, why: "looks like an absolute path" },
  { re: /\b(?:sk|ipk|isk|pk)_[A-Za-z0-9_-]{6,}/, why: "looks like a key" },
  { re: /@[\w.-]+\.\w{2,}/, why: "looks like an address" },
  { re: /https?:\/\//, why: "contains a URL" },
];

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.tsx?$/.test(e.name) && !e.name.endsWith(".generated.ts")) out.push(p);
  }
  return out;
}

export function collectSafeMessages() {
  const found = new Set();
  const refused = [];
  for (const file of ROOTS.flatMap((r) => walk(r))) {
    const src = readFileSync(file, "utf8");
    for (const m of src.matchAll(LITERAL)) {
      // Un-escape exactly what the JS parser would, so the string here is the
      // string at runtime — otherwise an escaped quote never matches.
      const text = m[2].replace(/\\(["'\\nrt])/g, (_, c) =>
        ({ n: "\n", r: "\r", t: "\t" })[c] ?? c,
      );
      const trimmed = text.trim();
      if (!trimmed) continue;
      const bad = SUSPECT.find((s) => s.re.test(trimmed));
      if (bad) { refused.push({ file, text: trimmed, why: bad.why }); continue; }
      found.add(trimmed);
    }
  }
  return { messages: [...found].sort(), refused };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { messages, refused } = collectSafeMessages();
  const body = `/**
 * GENERATED by \`npm run catalog:crash-messages\` — do not edit.
 *
 * §37: every message HappyVibe's own code throws as a PLAIN STRING LITERAL.
 * A literal cannot interpolate runtime data, which is the whole reason this set
 * may travel un-redacted; a message built by interpolation is refused by the
 * generator and stays redacted. Matched EXACTLY, never as a prefix.
 *
 * Re-run after adding a throw; \`tests/crash-safe-messages.test.ts\` re-derives
 * this from source and fails if the two disagree.
 */
export const SAFE_MESSAGES: ReadonlySet<string> = new Set([
${messages.map((m) => `  ${JSON.stringify(m)},`).join("\n")}
]);
`;
  writeFileSync(OUT, body, "utf8");
  console.log(`[crash-messages] ${messages.length} literal messages -> ${OUT}`);
  if (refused.length) {
    console.log(`[crash-messages] ${refused.length} refused (they stay redacted):`);
    for (const r of refused) console.log(`  ${r.why}: ${JSON.stringify(r.text)}  (${r.file})`);
  }
}
